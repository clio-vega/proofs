"""Export Python Phi (g4.phi_out, Def phi(3)) values to a Lean data file, |A/B| <= NMAX in boxes R,C <= BMAX.
Python cells are (c, r) [French]; Lean cells are (r, c).  Values are exported verbatim:
  f      : the LR tableau (values 1..l)
  phi    : g~ = phi_out(rot_revstd(f), Bv)  (values r+1 on row r)."""
import sys
sys.path.insert(0, '/home/clio/projects/proofs/code-1112c2-Q585'); sys.path.insert(0, '/home/clio/projects/proofs/code-1113-Q585-H1')
sys.path.insert(0, '/home/clio/projects/proofs/code-1113c2-Q585-G4')
from flock import lr_tableaux
from g4 import phi_out, rot_revstd
from g4_pure import partitions_in_box, parts_of
NMAX = int(sys.argv[1]); BMAX = int(sys.argv[2]); out = sys.argv[3]
rows = []
for R in range(1, BMAX + 1):
    for C in range(1, BMAX + 1):
        for A in partitions_in_box(R, C):
            for B in partitions_in_box(R, C):
                if any(B[i] > A[i] for i in range(R)): continue
                cells = {(c, r) for r in range(R) for c in range(B[r], A[r])}
                if not cells or len(cells) > NMAX: continue
                Bv = tuple(C - B[R - 1 - r] for r in range(R))
                for cont in parts_of(len(cells), R + C):
                    for f in lr_tableaux(cells, cont):
                        p = phi_out(rot_revstd(f, C, R), Bv)
                        rows.append((R, C, A, B, sorted(((r, c), v) for (c, r), v in f.items()),
                                     sorted(((r, c), v) for (c, r), v in p.items())))
def L(xs): return '[' + ', '.join(xs) + ']'
def cv(t): return L(f'(({r}, {c}), {v})' for (r, c), v in t)
with open(out, 'w') as fh:
    fh.write(f'-- generated by proofs/code-1120-lean-phi/export_phi.py {NMAX} {BMAX}; {len(rows)} instances\n')
    fh.write('-- (R, C, A, B, f, phi_python) ; cells (row, col)\n')
    fh.write('def phiData : List (ℕ × ℕ × List ℕ × List ℕ × List ((ℕ × ℕ) × ℕ) × List ((ℕ × ℕ) × ℕ)) := [\n')
    fh.write(',\n'.join(f'  ({R}, {C}, {L(map(str,A))}, {L(map(str,B))}, {cv(f)}, {cv(p)})' for R, C, A, B, f, p in rows))
    fh.write(']\n')
print(len(rows), 'instances; max |A/B|', max(len(r[4]) for r in rows))
