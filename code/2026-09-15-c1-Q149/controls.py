# ---- CONTROL 2: realisability of every occupancy word -----------------------
def realisability(emax=6, nmax=14):
    """Every u in {0,1}^{e-1} must occur as u_M(b,e) for some partition lambda."""
    ok = True
    for e in range(1, emax+1):
        seen = set()
        for n in range(0, nmax+1):
            for lam in partitions(n):
                for mu, u in ribbons_maya(lam, e):
                    seen.add(u)
        miss = set(all_words(e-1)) - seen
        print(f'  e={e}: {len(seen)}/{2**(e-1)} words realised by |lam|<={nmax}'
              + (f'   MISSING {sorted(miss)}' if miss else '   (all)'))
        ok &= not miss
    return ok

# ---- CONTROL 1: calibration to Q147 (height-only weights) -------------------
def calibration(pairs):
    """Substituting height-only weights W(u)=w_{|u|} must return EXACTLY the
    Q147 equation set, i.e. the locus w_z wbar_{u+v+1} + w_u wbar_{v+z} = 0."""
    for (e,f) in pairs:
        w  = {N: sp.Symbol(f'w{N}')  for N in range(e)}
        wb = {N: sp.Symbol(f'x{N}') for N in range(f)}
        W  = {u: w[sum(u)]  for u in all_words(e-1)}
        Wb = {y: wb[sum(y)] for y in all_words(f-1)}
        eqs,_,_ = commutator_eqs_window(e,f,Lw=e+f+1,W=W,Wb=Wb)
        got = {sp.expand(q) for q in eqs} | {sp.expand(-q) for q in eqs}
        # Q147 eq (B): w_z wbar_{u+v+1} + w_u wbar_{v+z}
        want = set()
        for u in range(e):
            for z in range(e):
                for v in range(f-e):
                    if v > f-e-1: continue
                    want.add(sp.expand(w[z]*wb[u+v+1] + w[u]*wb[v+z]))
        missing = {q for q in want if q not in got and sp.expand(-q) not in got}
        # every derived eq must lie in the Q147 ideal generated by `want`
        print(f'  ({e},{f}): derived {len(eqs)} eqs; Q147 relation (B) instances '
              f'contained = {len(want)-len(missing)}/{len(want)}')
        if missing: print('     MISSING:', list(missing)[:4])

