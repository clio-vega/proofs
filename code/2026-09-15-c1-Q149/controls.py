# ---- the predicted locus ----------------------------------------------------
def gamma_group(d, F):
    """all gamma: Z/d -> F^x with gamma(0)=1 and gamma(x)gamma(-x)=1"""
    units = [x for x in range(1,F)]
    out=[]
    reps=[]; seen={0}
    for x in range(1,d):
        if x in seen: continue
        seen.add(x); seen.add((-x)%d); reps.append(x)
    for vals in itertools.product(units, repeat=len(reps)):
        g={0:1}
        okflag=True
        for x,val in zip(reps,vals):
            g[x]=val; g[(-x)%d]=pow(val,F-2,F)
            if (2*x)%d==0 and (val*val)%F!=1: okflag=False
        if okflag: out.append(dict(g))
    # dedupe
    res=[]; seenk=set()
    for g in out:
        k=tuple(sorted(g.items()))
        if k not in seenk: seenk.add(k); res.append(g)
    return res

def predicted(e, f, F):
    d = gcd(e,f); out=set()
    for g in gamma_group(d, F):
        for al in range(1,F):
            W = tuple((al*  # prod (-gamma(j))^{u_j}
                       __import__('functools').reduce(lambda A,B:(A*B)%F,
                         [((-g[j % d]) % F) for j,uj in enumerate(u,1) if uj], 1)) % F
                      for u in all_words(e-1))
            for be in range(1,F):
                Wb = tuple((be*__import__('functools').reduce(lambda A,B:(A*B)%F,
                         [((-g[j % d]) % F) for j,yj in enumerate(y,1) if yj], 1)) % F
                      for y in all_words(f-1))
                out.add((W,Wb))
    return out

def exhaustive(e, f, F):
    """Brute force over F_F: ALL (W,Wbar) with [R_e,R_f]=0.  Compares to prediction."""
    Ws = weight_syms('W', e); Vs = weight_syms('V', f)
    eqs,_,_ = commutator_eqs_window(e,f,Lw=e+f+1)
    uw = all_words(e-1); yw = all_words(f-1)
    polys = [sp.Poly(q, *( [Ws[u] for u in uw] + [Vs[y] for y in yw] )) for q in eqs]
    terms = [[(m, int(c)%F) for m,c in zip(p.monoms(), p.coeffs())] for p in polys]
    nv = len(uw)+len(yw)
    sols=set()
    for vec in itertools.product(range(F), repeat=nv):
        good=True
        for tl in terms:
            s=0
            for m,c in tl:
                v=c
                for i,ex in enumerate(m):
                    if ex: v=(v*pow(vec[i],ex,F))%F
                s=(s+v)%F
            if s: good=False; break
        if good: sols.add((tuple(vec[:len(uw)]), tuple(vec[len(uw):])))
    zeroW = {(tuple([0]*len(uw)), tuple(v)) for v in itertools.product(range(F),repeat=len(yw))}
    zeroV = {(tuple(v), tuple([0]*len(yw))) for v in itertools.product(range(F),repeat=len(uw))}
    pred = predicted(e,f,F) | zeroW | zeroV
    print(f'  ({e},{f}) over F_{F}: |solutions|={len(sols)}  |predicted|={len(pred)}  '
          f'EQUAL={sols==pred}  extra={len(sols-pred)} missing={len(pred-sols)}')
    if sols-pred: print('     EXTRA sample:', list(sols-pred)[:3])
    if pred-sols: print('     MISSING sample:', list(pred-sols)[:3])
